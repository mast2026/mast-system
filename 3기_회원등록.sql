select s.nm, '3기', s.sch, 'member', 'active'
from src s
where not exists (
  select 1 from public.members m
  where m.name = s.nm and m.school = s.sch and m.gi = '3기'
);

-- 2) team_matching_members.mast_member_id 를 연결 (이름/학교 매칭 실패 방지)
update public.team_matching_members t
set mast_member_id = m.id
from public.members m
where t.generation::text = '3'
  and t.mast_member_id is null
  and m.gi = '3기'
  and m.name = t.name
  and m.school = t.school;

